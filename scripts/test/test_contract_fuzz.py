def alive(pid):
    """ps-stat based liveness (never kill -0 on a reaped/killed child): a zombie or a missing pid is not alive."""
    r = subprocess.run(["ps", "-o", "stat=", "-p", str(pid)], capture_output=True, text=True)
    st = r.stdout.strip()
    return bool(st) and not st.startswith("Z")


