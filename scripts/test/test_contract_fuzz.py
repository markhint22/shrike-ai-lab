def mutate(d, fn, old, new):
    path = os.path.join(d, fn)
    s = open(path).read()
    assert s.count(old) == 1, "mutation anchor not unique/present in %s: %r (%d)" % (fn, old, s.count(old))
    open(path, "w").write(s.replace(old, new))
    return path


