def leftovers():
    """Temp dirs / worktrees a run left behind (TMPDIR is private to the suite, so any entry is ours)."""
    left = [x for x in os.listdir(TMPD) if x.startswith(("cfuzz-", "qa-wt-"))]
    wl = subprocess.run(["git", "-C", STUB_REPO, "worktree", "list", "--porcelain"], capture_output=True, text=True).stdout
    n_wt = len([ln for ln in wl.splitlines() if ln.startswith("worktree ")])
    return left, n_wt


