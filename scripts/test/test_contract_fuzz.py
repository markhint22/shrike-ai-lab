def cron(ovn, extra_env=None, script=CRON, cwd=None, rel=None):
    env = {"PATH": "/usr/bin:/bin", "HOME": ovn, "OVN_DIR": ovn, "NTFY_SERVER": "http://127.0.0.1:9", "OVN_FUZZ_REPOS": "no-such-repo",
           "OVN_FUZZ_LOAD_MAX": "100000"}      # the suite must not depend on the host load: only the load cases lower the limit
    env.update(extra_env or {})
    cmd = ["bash", rel or script]
    p = subprocess.run(cmd, env=env, cwd=cwd, capture_output=True, text=True, timeout=120)
    log = os.path.join(ovn, "logs", "contract_fuzz.log")
    return p.returncode, (open(log).read() if os.path.exists(log) else "")


