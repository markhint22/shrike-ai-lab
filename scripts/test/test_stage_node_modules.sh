#!/usr/bin/env bash
# Regression test: ovn_stage_runner.sh's fresh `git worktree add` must get the main clone's
# node_modules symlinked in for every package.json BEFORE any step runs (2026-09-09).
#
# Real incident: a git worktree never includes gitignored content, so node_modules was always
# absent in the stage runner's temp worktree. Every PER-STEP frontend gate (ovn_autotest.sh)
# then failed with "Cannot find package 'vitest'" - misclassified as api-mismatch/no-edit/timeout
# instead of the real cause - permanently dooming any Vue/TS T3+ item regardless of code quality.
# full_verify() already had this fix for its OWN final check, but only ran it once at the very
# end, too late for any individual step. This extracts the real symlink block (added right after
# `git worktree add`, not a reimplementation) and proves it populates node_modules in a REAL
# worktree of a REAL repo with a REAL package.json, before any step-level code runs.
set -uo pipefail
SR="${OVN_STAGE_RUNNER:-$HOME/overnight-queue/ovn_stage_runner.sh}"
[ -f "$SR" ] || { echo "  SKIP: $SR not found on this host"; exit 0; }
P=0; F=0
ok(){ if eval "$2" >/dev/null 2>&1; then P=$((P+1)); else F=$((F+1)); echo "  FAIL: $1"; fi; }

BLOCK="$(sed -n '/^# 2026-09-09 FIX: a fresh `git worktree add`/,/^done < <(find "\$rd" -maxdepth 3 -name package.json/p' "$SR")"
[ -n "$BLOCK" ] || { echo "  FAIL: could not extract the node_modules symlink block from $SR"; exit 1; }
case "$BLOCK" in
  *'ln -s'*'node_modules'*) : ;;
  *) echo "  FAIL: extracted block doesn't look like the expected fix"; exit 1 ;;
esac

tmp="$(mktemp -d)"
git init -q --bare "$tmp/origin.git"
git clone -q "$tmp/origin.git" "$tmp/rd" 2>/dev/null
( cd "$tmp/rd"; git config user.email t@t; git config user.name t
  # node_modules must be GITIGNORED (as in every real repo here) so a fresh worktree
  # genuinely lacks it - the whole point of the fix being tested.
  echo "node_modules/" > .gitignore
  mkdir -p frontend
  echo '{"devDependencies":{"vitest":"1.0.0"}}' > frontend/package.json
  echo "export const x = 1" > frontend/index.ts
  git add -A; git commit -q -m init
  mkdir -p frontend/node_modules/vitest
  echo '{}' > frontend/node_modules/vitest/package.json
  git branch -M overnight/feature; git push -q origin overnight/feature )
git -C "$tmp/origin.git" symbolic-ref HEAD refs/heads/overnight/feature

rd="$tmp/rd"; wt="$(mktemp -d "$tmp/wt.XXXX")"; rm -rf "$wt"
git -C "$rd" fetch -q origin overnight/feature 2>/dev/null
git -C "$rd" worktree add -q "$wt" origin/overnight/feature
eval "$BLOCK"

ok "node_modules is symlinked into the fresh worktree's frontend dir" \
   "[ -L '$wt/frontend/node_modules' ]"
ok "the symlinked node_modules actually resolves to real content (vitest present)" \
   "[ -d '$wt/frontend/node_modules/vitest' ]"
ok "the worktree itself has NO real (non-symlink) node_modules copied in" \
   "[ -L '$wt/frontend/node_modules' ] || [ ! -e '$wt/frontend/node_modules' ]"

git -C "$rd" worktree remove --force "$wt" 2>/dev/null
rm -rf "$tmp"
echo "Stage node_modules provisioning: $P passed, $F failed"
[ "$F" -eq 0 ]
